// Generate .dependency-cruiser.json from the components.json files at both levels (ADR-0021).
// Never edit .dependency-cruiser.json by hand. `--check` fails when the committed file is stale.
//
// Usage: node tools/quality/js-ts/gen_depcruise.ts [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { allLevels, DEPCRUISE_CONFIG, pathsRegex, type Level, type Unit } from "./archgraph.ts";

interface Rule {
  name: string;
  comment: string;
  severity: "error";
  from: Record<string, unknown>;
  to: Record<string, unknown>;
}

const IGNORED = "(^|/)(node_modules|dist|coverage|\\.work|playwright-report|test-results)/";

const BASE_RULES: Rule[] = [
  {
    name: "no-circular",
    comment:
      "This file is generated by tools/quality/js-ts/gen_depcruise.ts from components.json " +
      "(ADR-0021); do not edit it. No module cycles (docs/architecture/metrics/README.md).",
    severity: "error",
    from: {},
    to: { circular: true },
  },
  {
    name: "not-to-unresolvable",
    comment: "Every import must resolve.",
    severity: "error",
    from: {},
    to: { couldNotResolve: true },
  },
  {
    name: "no-non-package-json",
    comment: "Every imported package is declared in a package.json.",
    severity: "error",
    from: {},
    to: { dependencyTypes: ["npm-no-pkg", "npm-unknown"] },
  },
];

function rule(name: string, comment: string, from: Unit, to: Record<string, unknown>): Rule {
  return { name, comment, severity: "error", from: { path: pathsRegex(from.paths) }, to };
}

function banned(unit: Unit, level: Level): Unit[] {
  return level.units.filter(
    (other) =>
      other.name !== unit.name &&
      other.paths.length > 0 &&
      !(level.isSystem && other.kind === "app") &&
      !unit.mayDependOn.includes(other.name),
  );
}

function publicRules(unit: Unit, level: Level): Rule[] {
  return level.units
    .filter((other) => unit.mayDependOn.includes(other.name) && other.public.length > 0)
    .map((other) =>
      rule(
        `${level.name}-${unit.name}-to-${other.name}-public-only`,
        `${unit.name} imports ${other.name} only through its public entry points.`,
        unit,
        { path: pathsRegex(other.paths), pathNot: pathsRegex(other.public) },
      ),
    );
}

function systemOnly(unit: Unit): Rule[] {
  const notOwn = { path: "^apps/", pathNot: pathsRegex(unit.paths) };
  if (unit.kind === "app") {
    return [
      rule(`system-${unit.name}-no-other-app`, "An app never imports another app.", unit, notOwn),
    ];
  }
  return [
    rule(`system-${unit.name}-no-app`, "A library never imports an app.", unit, { path: "^apps/" }),
  ];
}

function unitRules(unit: Unit, level: Level): Rule[] {
  if (unit.paths.length === 0) return [];
  const out = level.isSystem ? systemOnly(unit) : [];
  const others = banned(unit, level);
  if (others.length > 0) {
    out.push(
      rule(
        `${level.name}-${unit.name}-only-may-depend-on`,
        `${unit.name} imports only its mayDependOn: ${unit.mayDependOn.join(", ") || "nothing"}.`,
        unit,
        { path: pathsRegex(others.flatMap((other) => other.paths)) },
      ),
    );
  }
  return [...out, ...publicRules(unit, level)];
}

export function render(): string {
  const forbidden = [
    ...BASE_RULES,
    ...allLevels().flatMap((level) => level.units.flatMap((unit) => unitRules(unit, level))),
  ];
  const config = {
    forbidden,
    options: {
      doNotFollow: { path: "node_modules" },
      exclude: { path: IGNORED },
      tsPreCompilationDeps: true,
      combinedDependencies: true,
      enhancedResolveOptions: {
        extensions: [".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs", ".json"],
        conditionNames: ["import", "require", "node", "default", "types"],
        exportsFields: ["exports"],
        mainFields: ["module", "main", "types", "typings"],
      },
    },
  };
  return `${JSON.stringify(config, null, 2)}\n`;
}

function main(): number {
  const text = render();
  if (process.argv.includes("--check")) {
    const current = existsSync(DEPCRUISE_CONFIG) ? readFileSync(DEPCRUISE_CONFIG, "utf-8") : "";
    if (current !== text) {
      console.error(
        ".dependency-cruiser.json is stale: run node tools/quality/js-ts/gen_depcruise.ts",
      );
      return 1;
    }
    return 0;
  }
  writeFileSync(DEPCRUISE_CONFIG, text, "utf-8");
  return 0;
}

process.exitCode = main();
