// Generates src/api/schema.gen.ts, the TypeScript types of the API, from openapi.json
// (plan 0002, T23; ontology-builder/ADR-0011). Run it after `export_openapi.py`:
//   npm run gen:api --workspace apps/ontology-builder/web
// src/api/schema.drift.test.ts renders the same text and fails while the committed file differs.
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const SPEC = new URL("../openapi.json", import.meta.url);
const OUTPUT = new URL("../src/api/schema.gen.ts", import.meta.url);

const HEADER = `// Generated by \`npm run gen:api\` from openapi.json with openapi-typescript. Do not edit.
// src/api/schema.drift.test.ts fails while this file differs from a fresh generation.

`;

/** The text of src/api/schema.gen.ts for the current openapi.json, formatted like the repo. */
export async function render(): Promise<string> {
  const types = astToString(await openapiTS(SPEC));
  const options = (await resolveConfig(OUTPUT)) ?? {};
  return format(HEADER + types, { ...options, parser: "typescript" });
}

if (import.meta.main) {
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- the fixed OUTPUT above
  await writeFile(OUTPUT, await render());
}
